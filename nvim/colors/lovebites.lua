-- Live light/dark: Ghostty swaps its own theme with macOS appearance. Re-ask the terminal
-- for its background (OSC 11); Neovim's built-in handler then sets 'background', which
-- reloads this colorscheme in the matching palette.
if not vim.g.lovebites_watch and #vim.api.nvim_list_uis() > 0 then
  vim.g.lovebites_watch = true
  local ask = function()
    if vim.g.colors_name == "lovebites" then vim.api.nvim_ui_send("\27]11;?\7") end
  end
  vim.api.nvim_create_autocmd("FocusGained", { callback = ask })
  vim.uv.new_timer():start(3000, 3000, vim.schedule_wrap(ask))
end
